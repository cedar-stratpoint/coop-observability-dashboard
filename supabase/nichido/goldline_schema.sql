-- Goldline (Nichido) schema for the dedicated Nichido Supabase project.
--
-- Goldline's data used to live in the shared Coop archive project as gl_* tables. In
-- this project it is the only tenant, so the tables, view and functions drop the gl_
-- prefix (archive gl_sales = here sales, gl_commit_batch = commit_batch, and so on).
-- This file is the source of truth for the Nichido project: it rebuilds every object
-- as it exists on the archive (the goldline*.sql files plus the hand-added
-- uploads.error_detail column), so scripts/nichido/migrate-goldline.ts can move rows
-- over unchanged. An existing project created with the old gl_ names is converted by
-- supabase/nichido/rename_drop_gl_prefix.sql.
--
-- Differences from the archive, on purpose:
--   * `companies` here is a one-row MIRROR (just 'goldline') so the foreign keys and
--     the analytics company-name lookup keep working. Sign-in, memberships and the
--     company registry stay in the archive project (src/company.ts, auth.ts).
--   * sales.id / inventory.id are `generated by default` (archive: `always`) so the
--     copy keeps their ids; app inserts never send an id, so nothing else changes.
--   * company_digest_archive / company_business_health are not created (unused).
--   * No sample supply seed: the copy brings the edited values across.
--
-- RLS on with no policies and revoked from anon/authenticated on every table: only
-- the service role (the Coop server) gets through. Functions are security invoker and
-- executable by service_role only. Run on Nichido STAGING first, PROD after review.
-- The private storage bucket `goldline-uploads` is created at the end.
--
-- Sales money is encrypted at rest AFTER this file: it creates sales with plain
-- gross_retail / net_of_vat (what migrate-goldline.ts copies into), then
-- s1_sales_encryption.sql moves them into sales.amounts_enc with a Vault key and
-- replaces sales_rollup / sales_by_sku, and s2_sales_drop_plaintext.sql drops the plain
-- columns. A fresh project: this file → (copy) → s1 → s2. The two functions below are
-- the pre-encryption versions; s1 holds the live ones.

